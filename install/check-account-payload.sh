#!/bin/sh
# Account payload check (#75), chained into core/claude/hooks/pre-commit
# through the local git config harness.preCommitChain. Opt-in per clone, and
# meant only for the clone on the workstation that exports the account layer.
#
# IT RUNS FROM AN INSTALLED COPY, NEVER FROM THE WORK TREE
# The chain point only runs a script that sits in the hook directory, which in
# this repository is the main checkout's gitignored .claude/hooks/, shared by
# every worktree through core.hooksPath. That directory is installer output,
# and git does not write ignored paths on a checkout or merge. This script in
# turn runs the exporter that sits beside it, never the one in the work tree.
# Install the copy from the main checkout at a commit you have reviewed, and
# copy again after any of the four files changes:
#
#   cp install/check-account-payload.sh install/Export-Account.ps1 \
#      install/AccountShared.ps1 install/Restore-ClaudeProject.ps1 .claude/hooks/
#   git config --local harness.preCommitChain check-account-payload.sh
#
# A stale copy fails closed: an export from an older exporter differs from the
# payload a newer one wrote, and the commit is refused until the copy is
# refreshed.
#
# account/claude/ is generated by install/Export-Account.ps1 and never
# hand-edited. Until this check that rule was prose. When a commit stages any
# path under account/claude/, this script runs a fresh export into a temp
# directory and refuses the commit if a staged account/claude path differs
# from what the export wrote there. A staged deletion of a path the export
# still writes refuses, and so does a staged path the export does not write.
# Content and mode both count: an entry whose index mode (100644, 100755 or
# 120000) differs from the export's refuses, even when the blob is identical.
#
# Only staged paths are compared, not the whole payload. Drift elsewhere (the
# account source has moved on since the last export) is not this commit's to
# fix, and refusing on it would block every narrow payload commit until a full
# re-export landed.
#
# THE COMPARISON GOES THROUGH GIT'S FILTERS
# Raw bytes are the wrong instrument. core.autocrlf and the account/claude/**
# eol rule in .gitattributes give the same content more than one spelling on
# disk. The export is added to a throwaway repository that carries the staged
# .gitattributes, and its blob ids are compared with the staged blob ids. Equal
# ids mean that `git add` of the fresh export would stage exactly what is
# staged now.
#
# GIT'S HOOK ENVIRONMENT IS CLEARED FIRST
# git exports GIT_INDEX_FILE, and GIT_DIR in a worktree, to every hook. A
# `git add` in the throwaway repository that inherited them would write the
# export into the commit's own index. Every git call against the throwaway
# repository runs in a subshell that unsets them. The exporter keeps them. Its
# only git call would resolve the main checkout, and this script passes that as
# -CoreRepo instead, so the exporter reads no git state at all.
#
# FAIL-CLOSED
# Nothing staged under account/claude/: exit 0 before anything else runs, so
# commits that do not touch the payload pay one git call.
# No Export-Account.ps1 beside this script: refuse. The copy is incomplete,
# and a staged payload with nothing to compare it with cannot be told apart
# from a hand edit. The work tree's exporter is never a fallback.
# pwsh or the account source (~/.claude) is missing: refuse. The payload is
# generated only from that source, so a staged change that cannot be compared
# with a fresh export cannot be told apart from a hand edit. Only a clone
# whose owner opted in runs this, and that is meant to be the exporting
# workstation, so this refusal means the machine lost something the export
# needs. Commits that stage nothing under account/claude/ are never refused
# here, on any machine.
# The export itself fails: refuse. The exporter carries the identity and
# personal-term gates for the payload, and a refusal there is a payload that
# must not be committed.
#
# NEVER PRINTS FILE CONTENTS
# Only staged paths are named, and the identity gate in pre-commit has checked
# those paths before this runs. The exporter's own output goes to a log in the
# temp directory and is not repeated, because it names the account home, which
# is a profile path.

set -u

refuse() {
  echo "pre-commit: refused. $1" >&2
  exit 1
}

# Resolved before any cd, so a relative $0 still names this script's directory.
script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd) ||
  refuse "The account payload check could not resolve its own directory."
exporter="$script_dir/Export-Account.ps1"
exporter_src=install/Export-Account.ps1

# :(top) so the pathspec means the same thing from any directory. Paths come
# back relative to the top of the work tree either way.
staged=$(git -c core.quotePath=false diff --cached --raw --no-renames --no-abbrev -- ':(top)account/claude/') ||
  refuse "The account payload check could not list the staged account/claude paths."
[ -n "$staged" ] || exit 0

# git quotes a name holding a tab, a double quote, a backslash or another
# control character even under core.quotePath=false. The quoted form names no
# file in the export, so it cannot be compared.
tab=$(printf '\t')
case "$staged" in
  *"$tab\""*) refuse "A staged account/claude path needs quoting (tab, double quote, backslash or control character), so it cannot be compared with the export. Rename it at the source, re-export, then re-stage." ;;
esac

top=$(git rev-parse --show-toplevel) ||
  refuse "The account payload check could not find the top of the work tree."
cd "$top" || refuse "The account payload check could not enter the top of the work tree."

[ -f "$exporter" ] ||
  refuse "This commit stages account/claude paths, and there is no Export-Account.ps1 beside the check script, so they cannot be compared with a fresh export. Copy $exporter_src, install/AccountShared.ps1 and install/Restore-ClaudeProject.ps1 from a reviewed checkout into the directory this script runs from (.claude/hooks/ in the documented install)."

# The main checkout, passed to the exporter as -CoreRepo. Its own default
# derives it from the exporter's location, which is the installed copy here.
git_common=$(git rev-parse --path-format=absolute --git-common-dir) ||
  refuse "The account payload check could not find the main checkout."
core_repo=$(dirname "$git_common")

account_home="${USERPROFILE:-$HOME}/.claude"
[ -d "$account_home" ] ||
  refuse "This commit stages account/claude paths, and this machine has no account source at ~/.claude to export them from. account/claude is generated by $exporter_src on the workstation that holds that source, never hand-edited. Make the change there."

pwsh_bin=$(command -v pwsh) ||
  refuse "This commit stages account/claude paths, and pwsh is not on PATH, so $exporter_src cannot run to check them."

work=$(mktemp -d) || refuse "The account payload check could not create a temp directory."
trap 'rm -rf "$work"' EXIT

printf '%s\n' "$staged" >"$work/staged"
# The staged .gitattributes, so the export is hashed under the rules this
# commit carries. A tree without one hashes with git's defaults.
git show ':0:.gitattributes' >"$work/gitattributes" 2>/dev/null || : >"$work/gitattributes"

mkdir -p "$work/repo/account" || refuse "The account payload check could not create a temp directory."
"$pwsh_bin" -NoProfile -NonInteractive -File "$exporter" \
  -ClaudeHome "$account_home" -OutputRoot "$work/repo/account/claude" \
  -CoreRepo "$core_repo" >"$work/export.log" 2>&1
export_rc=$?
[ "$export_rc" -eq 0 ] ||
  refuse "The fresh export failed (exit $export_rc), so the staged account/claude paths cannot be checked. Run pwsh -NoProfile -File $exporter_src to see why. Its output is not repeated here because it names the account home."

(
  unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_COMMON_DIR GIT_OBJECT_DIRECTORY \
    GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_PREFIX GIT_NAMESPACE
  cd "$work/repo" &&
    git init -q &&
    cp "$work/gitattributes" .gitattributes &&
    git -c core.safecrlf=false add -A -f -- account/claude &&
    git -c core.quotePath=false ls-files --stage -- account/claude >"$work/exported"
) || refuse "The account payload check could not hash the fresh export."

# exported: "<mode> <blob> <stage>\t<path>". staged (diff --raw):
# ":<old mode> <new mode> <old blob> <new blob> <status>\t<path>", where an
# all-zero new blob means the path is deleted in the index. A path missing from
# either side compares as an empty id and an empty mode. The index mode is
# compared as well as the blob, because a mode-only change (the executable bit,
# a file turned symlink with the same bytes) leaves the blob id unchanged.
mismatched=$(awk -F '\t' '
  FILENAME == ARGV[1] {
    split($1, m, " ")
    exported[$2] = m[2]
    exported_mode[$2] = m[1]
    next
  }
  {
    split($1, m, " ")
    s = m[4]
    sm = m[2]
    if (s ~ /^0+$/) { s = ""; sm = "" }
    e = ($2 in exported) ? exported[$2] : ""
    em = ($2 in exported) ? exported_mode[$2] : ""
    if (s != e || sm != em) print $2
  }
' "$work/exported" "$work/staged") || refuse "The account payload check could not compare the export with the staged paths."

if [ -n "$mismatched" ]; then
  {
    echo "pre-commit: refused. These staged account/claude paths differ from a fresh export of the account source:"
    printf '%s\n' "$mismatched" | while IFS= read -r p; do echo "  $p"; done
    echo "  account/claude is generated by $exporter_src and never hand-edited. Make the change under ~/.claude,"
    echo "  re-export, and stage what the export wrote. File contents are deliberately not printed."
  } >&2
  exit 1
fi
exit 0
